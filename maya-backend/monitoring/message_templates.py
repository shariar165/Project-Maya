def get_template(concern_type: str, trimester: str) -> str:
    candidates = TEMPLATES.get(concern_type, {}).get(trimester, [])
    if not candidates:
        candidates = TEMPLATES.get(concern_type, {}).get("second", [])
    if not candidates:
        return _GENERIC_FALLBACK
    return random.choice(candidates)
